"""Bundle the normative MCP catalog and payload schemas; --check verifies copies."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    catalog = json.loads((ROOT / "docs/mcp/local-connector/1.0.tools.json").read_text())
    protocols = ("agent-profile", "agent-discourse", "agent-knowledge")
    schemas = {
        protocol + "/1.0": json.loads(
            (ROOT / f"docs/protocols/{protocol}/1.0.schema.json").read_text()
        )
        for protocol in protocols
    }
    packs = json.loads((ROOT / "docs/protocols/agent-discourse/1.0.packs.json").read_text())
    data = {"tools": catalog, "schemas": schemas, "packs": packs}
    rust = ROOT / "crates/agent-protocols/src/local_connector/catalog.json"
    ts = ROOT / "packages/agent-protocols/src/local-connector/catalog-data.ts"
    if args.check:
        assert json.loads(rust.read_text()) == data, f"stale {rust}"
        source = ts.read_text()
        bundled = json.loads(source[source.index("=") + 1 :].strip().removesuffix(";"))
        assert bundled == data, f"stale {ts}"
        return
    encoded = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    rust.write_text(encoded + "\n")
    ts.write_text("// Generated by scripts/sync_connector_catalog.py. Do not edit.\n"
                  "// prettier-ignore\nexport const CONNECTOR_CATALOG = " + encoded + ";\n")


if __name__ == "__main__":
    main()
